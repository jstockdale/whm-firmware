#define GLYPH_ROWS 8

/* BUGFIX: the clip sentinel was 0xFFFF, which casts to -1 as int16_t and
 * culled every pixel outside marquee-drawn regions (blank titles, v0.4.2/3).
 * Sentinel is now INT16_MAX and comparisons run in int. */
static int16_t s_clip_x0 = 0;
static int16_t s_clip_x1 = INT16_MAX;

void gfx_set_clip(uint16_t x0, uint16_t x1)
{
    s_clip_x0 = (int16_t)x0;
    s_clip_x1 = (x1 > INT16_MAX) ? INT16_MAX : (int16_t)x1;
}
void gfx_clear_clip(void) { s_clip_x0 = 0; s_clip_x1 = INT16_MAX; }


