/* ---- proportional metrics: per-glyph ink bounds, computed once ----
 * Digits are forced to full-cell "tabular figures" so clocks and counters
 * never jiggle as values change. Space advances 3px. */
typedef struct { uint8_t l, w; } glyph_m_t;
static glyph_m_t s_m[95];
static bool s_m_ready = false;

static void metrics_init(void)
{
    if (s_m_ready) return;
    for (int gi = 0; gi < 95; gi++) {
        uint8_t bits = 0;
        for (int r = 0; r < GLYPH_ROWS; r++) bits |= k_font[gi * GLYPH_ROWS + r];
        char ch = (char)(0x20 + gi);
        if (ch >= '0' && ch <= '9') { s_m[gi].l = 0; s_m[gi].w = 5; continue; }
        if (bits == 0) { s_m[gi].l = 0; s_m[gi].w = 3; continue; }   /* space */
        int first = 0, last = 4;
        while (!(bits & (0x80 >> first))) first++;
        while (!(bits & (0x80 >> last))) last--;
        s_m[gi].l = (uint8_t)first;
        s_m[gi].w = (uint8_t)(last - first + 1);
    }
    s_m_ready = true;
}

/* draws the glyph's ink starting at x; returns the advance in pixels */
uint16_t gfx_char(int16_t x, uint16_t y, char c, uint8_t scale,
                  uint8_t r, uint8_t g, uint8_t b)
{
    metrics_init();
    if (c < 0x20 || c > 0x7E) c = '?';
    int gi = c - 0x20;
    const uint8_t *gl = &k_font[gi * GLYPH_ROWS];
    const glyph_m_t m = s_m[gi];
    for (int row = 0; row < GLYPH_ROWS; row++) {
        uint8_t bits = gl[row];
        if (!bits) continue;
        for (int col = m.l; col < m.l + m.w; col++) {
            if (bits & (0x80 >> col)) {
                int px = x + (col - m.l) * scale;
                if (px < 0 || px + (int)scale <= (int)s_clip_x0 ||
                    px >= (int)s_clip_x1) continue;
                whm_display_fill_rect((uint16_t)px, y + row * scale,
                                      scale, scale, r, g, b);
            }
        }
    }
    return (uint16_t)((m.w + 1) * scale);
}

void gfx_text(int16_t x, uint16_t y, const char *s, uint8_t scale,
              uint8_t r, uint8_t g, uint8_t b)
{
    while (*s) {
        x += (int16_t)gfx_char(x, y, *s++, scale, r, g, b);
    }
}

uint16_t gfx_text_width(const char *s, uint8_t scale)
{
    metrics_init();
    if (!*s) return 0;
    uint32_t w = 0;
    while (*s) {
        char c = *s++;
        if (c < 0x20 || c > 0x7E) c = '?';
        w += (uint32_t)(s_m[c - 0x20].w + 1);
    }
    return (uint16_t)((w - 1) * scale);   /* no gap after the last glyph */
}

void gfx_text_center(uint16_t cx, uint16_t y, const char *s, uint8_t scale,
                     uint8_t r, uint8_t g, uint8_t b)
{
    uint16_t w = gfx_text_width(s, scale);
    uint16_t x = (cx > w / 2) ? (cx - w / 2) : 0;
    gfx_text(x, y, s, scale, r, g, b);
}
