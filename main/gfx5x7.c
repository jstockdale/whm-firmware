/*
 * gfx5x7.c - minimal text renderer for the WHM display.
 *
 * 5x8 bitmap font (5x7 + descender row), ASCII 0x20-0x7E. Glyph bitmaps
 * extracted from Waveshare's ESP32-S3-RGB-Matrix example repo
 * (components/font/Font_5x7, Apache-2.0). One byte per row, 8 rows per
 * glyph (row 8 used only by g/j/p/q/y descenders), MSB-first, upper 5
 * bits valid. Recommended line pitch: 8px (descenders share the gap row),
 * 9-10px for airy layouts.
 */
#include "gfx5x7.h"
